/** Older Firefox names for the same keys. */
const ALIASES: Record<string, string> = {
  OSLeft: 'MetaLeft',
  OSRight: 'MetaRight',
  VolumeMute: 'AudioVolumeMute',
  VolumeDown: 'AudioVolumeDown',
  VolumeUp: 'AudioVolumeUp',
};

export function scancode(code: string): number | undefined {
  return BASE[code] ?? BASE[ALIASES[code] ?? ''];
}

